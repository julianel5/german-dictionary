def test_scan_en_keeps_homonyms_separate_and_detects_form_uses(tmp_path: Path) -> None:
    en = tmp_path / "en.jsonl.gz"
    _write_jsonl(en, [_bank(1, with_de=True), _bank(2, with_de=False), _go()])
    lemmas = [
        {"word": "bank", "category": "noun"},
        {"word": "went", "category": "verb"},
    ]
    scan = pilot.Scan()
    lemma_records, form_uses = common.scan_en_lemma_records(en, lemmas, scan)
    assert len(lemma_records["bank"]) == 2  # both etymologies survive, never merged
    assert sorted(k for k, _ in lemma_records["bank"]) == [
        "bank\tnoun\t1",
        "bank\tnoun\t2",
    ]
    assert lemma_records["went"] == []
    assert form_uses["went"] == ["go\tverb\t0"]


