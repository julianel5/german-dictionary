def test_attach_freedict_exclusive_buckets() -> None:
    fd_index = {
        "house": [{"text": "Haus", "gen": "neut"}],
        "purple": [{"text": "lila", "gen": None}],
    }
    house = {"norm_word": "house", "has_de": True, "fd_de_count": 0}
    car = {"norm_word": "car", "has_de": True, "fd_de_count": 0}
    purple = {"norm_word": "purple", "has_de": False, "fd_de_count": 0}
    seldom = {"norm_word": "seldom", "has_de": False, "fd_de_count": 0}
    expected = [
        (house, "both"),
        (car, "en_only"),
        (purple, "freedict_only"),
        (seldom, "neither"),
    ]
    for lemma, bucket in expected:
        common.attach_freedict(lemma, fd_index)
        assert lemma["exclusive"] == bucket
    assert house["fd_de_count"] == 1
    assert house["fd_genders"] == 1


