def test_end_to_end_main(tmp_path: Path) -> None:
    en = tmp_path / "en.jsonl.gz"
    de = tmp_path / "de.jsonl.gz"
    freedict = tmp_path / "fd.tei"
    lemmas = tmp_path / "lemmas.tsv"
    report = tmp_path / "common-words-coverage.json"
    _write_jsonl(
        en,
        [_house(), _car(), _seldom(), _purple(), _go()],
    )
    _write_jsonl(de, [_de_record()])
    freedict.write_text(
        _fd_tei([("house", "Haus", "neut"), ("purple", "lila", "m")]),
        encoding="utf-8",
    )
    _lemmas_file(
        lemmas,
        [
            "house\tnoun",
            "car\tnoun",
            "seldom\tadv",
            "purple\tadj",
            "went\tverb",
            "zzz\tnoun",
        ],
    )
    argv = [
        "--en", str(en),
        "--de", str(de),
        "--freedict", str(freedict),
        "--lemmas", str(lemmas),
        "--report", str(report),
    ]
    assert common.main(argv) == 0
    payload = json.loads(report.read_text(encoding="utf-8"))

    assert payload["metrics"]["all"]["lemmas_scored"]["status"] == "MEASURED"
    counts = payload["counts"]
    assert counts["lemmas_requested"] == 6
    assert counts["lemmas_unique"] == 6
    assert counts["lemmas_with_records"] == 4
    assert counts["lemmas_missing_from_en"] == 2  # "went" (inflected-only) and "zzz"
    assert counts["lemmas_inflected_only_nonheadword"] == 1  # "went" is a form of "go"

    all_metrics = payload["metrics"]["all"]
    # among the 6 lemmas, house+car carry German from en.wiktionary
    assert all_metrics["en_de_coverage"]["numerator"] == 2
    assert all_metrics["en_de_coverage"]["denominator"] == 6
    # purple has no en German but has FreeDict; house has en German + FreeDict
    assert all_metrics["freedict_de_coverage"]["numerator"] == 2
    assert all_metrics["any_source_de_coverage"]["numerator"] == 3  # house, car, purple

    noun_metrics = payload["metrics"]["per_category"]["noun"]["en_de_coverage"]
    assert noun_metrics["numerator"] == 2
    assert noun_metrics["denominator"] == 3  # house, car, zzz (missing) carry the noun tag

    assert payload["exclusive_contribution"]["counts"] == {
        "en_only": 1,       # car
        "freedict_only": 1,  # purple
        "both": 1,           # house
        "neither": 3,        # seldom, went, zzz
    }
    assert payload["freedict"]["status"] == "MEASURED"
    assert payload["de_enrichment"]["matched"] == 1  # Haus
    assert payload["scans"]["en"]["parse_errors"] == 0
    assert payload["recommendation"]["production_import"] == "NO_GO"
    assert payload["recommendation"]["remaining_blockers"] == ["L1", "L3", "L4"]
    assert payload["licences"]["freedict_eng_deu"].startswith("VERIFIED")
    assert payload["inputs"]["lemmas"]["header"][0].startswith("generated by")